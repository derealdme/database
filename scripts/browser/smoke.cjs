const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const failures=[];page.on('pageerror',e=>failures.push(e.message));
 await page.goto(process.env.BASE_URL || 'http://127.0.0.1:8000');
 await page.getByRole('button',{name:'AAPL Apple Inc.'}).waitFor({timeout:120000});
 await page.getByRole('button',{name:'AAPL Apple Inc.'}).click();
 await page.getByRole('heading',{name:'Metric breakdown'}).waitFor();
 await page.getByLabel('Research note').fill('Browser integration test');
 await page.getByRole('button',{name:'Add note',exact:true}).click();
 await page.getByText('Browser integration test',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Edit',exact:true}).last().click();
 await page.getByLabel('Research note').fill('Edited browser test');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await page.getByText('Edited browser test',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Delete note'}).last().click();
 await page.getByText('Edited browser test',{exact:true}).waitFor({state:'detached'});
 await page.getByRole('button',{name:'Back to explorer'}).click();
 await page.getByLabel('Compare AAPL',{exact:true}).check();
 await page.getByLabel('Compare MSFT',{exact:true}).check();
 await page.getByRole('button',{name:'Compare (2)',exact:true}).click();
 await page.locator('th').filter({hasText:/^MSFT$/}).waitFor();
 await page.getByRole('button',{name:'Portfolio',exact:true}).click();
 await page.getByLabel('Portfolio name').fill('Browser test portfolio');
 await page.getByRole('button',{name:'Create with $100,000'}).click();
 await page.getByRole('heading',{name:'Browser test portfolio',exact:true}).waitFor();
 await page.getByRole('button',{name:'Place simulated trade'}).click();
 await page.getByText('Simulated trade recorded.',{exact:true}).waitFor();
 await page.getByLabel('Trade side').selectOption('SELL');
 await page.getByRole('button',{name:'Place simulated trade'}).click();
 await page.getByRole('cell',{name:'SELL',exact:true}).waitFor();
 page.once('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Delete',exact:true}).click();
 await page.getByRole('heading',{name:'Browser test portfolio',exact:true}).waitFor({state:'detached'});
 await page.getByRole('button',{name:'News',exact:true}).click();
 await page.getByLabel('News ticker').fill('AAPL');
 await page.getByRole('button',{name:'Filter news',exact:true}).click();
 await page.locator('.news-list article').first().waitFor();
 await page.getByRole('button',{name:'Explore',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 console.log(JSON.stringify({browserErrors:failures,mobileDocumentOverflow:overflow,flows:['stock details','note create/edit/delete','compare','portfolio create/buy/sell/delete','news filter']},null,2));
 await browser.close();if(failures.length||overflow)process.exit(1);
})().catch(error=>{console.error(error);process.exit(1)});
